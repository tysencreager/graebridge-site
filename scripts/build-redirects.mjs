// Runs before every build (npm "prebuild"). Writes:
//   public/.htaccess   Apache rules for SiteGround: https+www, the Hibu 301 map, 404 page, caching
//   public/_redirects  the same 301 map for Cloudflare Pages (staging), which ignores .htaccess
import fs from 'node:fs';

const src = fs.readFileSync('data/htaccess-redirects.txt', 'utf8').split(/\r?\n/);
const fixed = [];
const out = src.map((line) => {
  const m = line.match(/^RedirectMatch 301 (\(\?i\))?\^(\/[^ ]*?)\/\?\$ (\S+)$/);
  if (!m) return line;
  const [, ci = '', from, to] = m;
  // A rule whose target matches its own pattern (/kitchen-countertops -> /kitchen-countertops/) would loop
  // forever in Apache. Match only the no-trailing-slash form for those.
  if (to.replace(/#.*$/, '').replace(/\/$/, '') === from) {
    fixed.push(from);
    return `RedirectMatch 301 ${ci}^${from}$ ${to}`;
  }
  return line;
});

const htaccess = `# GENERATED by scripts/build-redirects.mjs from data/htaccess-redirects.txt. Edit the source, not this file.
Options -Indexes
DirectoryIndex index.html
DirectorySlash On
ErrorDocument 404 /404.html

${out.join('\n').trim()}

# Long cache for fingerprinted build assets and fonts; HTML is always revalidated
<IfModule mod_headers.c>
  <FilesMatch "\\.(html)$">
    Header set Cache-Control "public, max-age=0, must-revalidate"
  </FilesMatch>
  <If "%{REQUEST_URI} =~ m#^/(_astro|fonts)/#">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </If>
  Header always set X-Content-Type-Options "nosniff"
  Header always set Referrer-Policy "strict-origin-when-cross-origin"
</IfModule>
<IfModule mod_expires.c>
  ExpiresActive On
  ExpiresByType image/avif "access plus 1 year"
  ExpiresByType image/webp "access plus 1 year"
  ExpiresByType image/jpeg "access plus 1 month"
  ExpiresByType image/png "access plus 1 month"
  ExpiresByType image/svg+xml "access plus 1 month"
  ExpiresByType font/woff2 "access plus 1 year"
  ExpiresByType text/css "access plus 1 year"
  ExpiresByType application/javascript "access plus 1 year"
</IfModule>
<IfModule mod_mime.c>
  AddType image/avif .avif
  AddType font/woff2 .woff2
  AddType application/manifest+json .webmanifest
</IfModule>
<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css application/javascript application/json image/svg+xml text/xml application/xml
</IfModule>
`;
fs.mkdirSync('public', { recursive: true });
fs.writeFileSync('public/.htaccess', htaccess);

// Cloudflare Pages: one line per old URL, with and without a trailing slash.
const rows = fs.readFileSync('data/redirects.csv', 'utf8').trim().split(/\r?\n/).slice(1);
const lines = [];
for (const row of rows) {
  const [from, to] = row.split(',');
  if (!from || !to || from === '/') continue;
  if (from.replace(/\/$/, '') === to.replace(/\/$/, '')) continue; // Pages adds the trailing slash itself
  lines.push(`${from} ${to} 301`, `${from}/ ${to} 301`);
  if (from !== from.toLowerCase()) lines.push(`${from.toLowerCase()} ${to} 301`, `${from.toLowerCase()}/ ${to} 301`);
}
fs.writeFileSync('public/_redirects', `# GENERATED by scripts/build-redirects.mjs from data/redirects.csv (Cloudflare Pages staging)\n${lines.join('\n')}\n`);

console.log(`redirects: .htaccess written (${out.filter((l) => l.startsWith('RedirectMatch')).length} rules, ${fixed.length} self-redirect loops fixed: ${fixed.join(', ')}); _redirects written (${lines.length} lines)`);
